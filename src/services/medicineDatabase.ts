// Helper search function across brand name, generic name, category, and type
export function searchMedicines(query: string, preferredCategory?: 'skin' | 'dental'): MedicineItem[] {
  const clean = query.trim().toLowerCase();
  if (!clean) {
    if (preferredCategory) {
      return MEDICINE_DATABASE.filter(
        (m) => m.category === preferredCategory || (preferredCategory === 'skin' && m.category === 'hair')
      ).slice(0, 15);
    }
    return MEDICINE_DATABASE.slice(0, 15);
  }

  const terms = clean.split(/\s+/).filter(Boolean);

  const matched = MEDICINE_DATABASE.filter((item) => {
    const target = `${item.name} ${item.brand || ''} ${item.generic} ${item.type} ${item.category}`.toLowerCase();
    return terms.every((t) => target.includes(t));
  });

  // Sort: exact startsWith names first, then preferred category
  return matched.sort((a, b) => {
    const aStarts = a.name.toLowerCase().startsWith(clean);
    const bStarts = b.name.toLowerCase().startsWith(clean);
    if (aStarts && !bStarts) return -1;
    if (!aStarts && bStarts) return 1;

    if (preferredCategory) {
      const aPref = a.category === preferredCategory;
      const bPref = b.category === preferredCategory;
      if (aPref && !bPref) return -1;
      if (!aPref && bPref) return 1;
    }
    return 0;
  });
}
